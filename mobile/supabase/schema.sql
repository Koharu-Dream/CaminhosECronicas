-- Caminhos e Crônicas — banco de dados (Supabase / PostgreSQL)

-- 1) Tabelas ---------------------------------------------------------------

create table if not exists public.npcs (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  race        text,
  occupation  text,
  location    text,
  personality text,
  notes       text,
  created_at  timestamptz not null default now()
);

-- Uma linha por campanha; `data` guarda a viagem e o histórico (JSON).
create table if not exists public.journeys (
  campaign_id text primary key,
  data        jsonb not null,
  updated_at  timestamptz not null default now()
);

-- 2) Segurança (Row Level Security) ---------------------------------------

alter table public.npcs enable row level security;
alter table public.journeys enable row level security;

grant select, insert, update, delete on public.npcs to anon, authenticated;
grant select, insert, update, delete on public.journeys to anon, authenticated;

drop policy if exists "npcs_acesso_publico" on public.npcs;
create policy "npcs_acesso_publico" on public.npcs
  for all to anon, authenticated
  using (true) with check (true);

drop policy if exists "journeys_acesso_publico" on public.journeys;
create policy "journeys_acesso_publico" on public.journeys
  for all to anon, authenticated
  using (true) with check (true);

