-- 4) Avisos do Mestre (MOBILE_009: Realtime + notificações) ---------------

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;

grant select, insert on public.notifications to anon, authenticated;

drop policy if exists "Enabled read/write for all users" on public.notifications;
create policy "Enabled read/write for all users" on public.notifications
  for all to public
  using (true) with check (true);

-- Liga o Realtime para a tabela (equivale a "Enable Realtime" no painel).
do $$
begin
  alter publication supabase_realtime add table public.notifications;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;
